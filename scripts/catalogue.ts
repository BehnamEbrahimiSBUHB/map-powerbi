// Writes docs/map-files.md: every map file with its shape count and links,
// grouped by map set, plus the layer each one comes from.
//
// Usage: bun run scripts/catalogue.ts   (run after `bun run build`)

import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { MAP_GROUPS, outputStem, syntheticFile, type MapGroup } from "./paths.ts";
import { ALL_TYPES, MAP_SETS, type Level, type Source } from "./sources.ts";

const ROOT = join(import.meta.dir, "..");
const OUTPUT = join(ROOT, "docs", "map-files.md");
/** The Power BI Shape map visual plots no more areas than this. */
const MAX_AREAS = 1500;

const LEVEL_NAMES: Readonly<Record<Level, string>> = {
  oa: "OA",
  lsoa: "LSOA",
  msoa: "MSOA",
  council: "Council",
  "health-board": "Health board",
  cluster: "Cluster",
};
const PROVIDER_NAMES: Readonly<Record<Source["provider"], string>> = {
  ons: "ONS Open Geography Portal",
  datamapwales: "DataMapWales (Welsh Government)",
};

// ---------- pure helpers ----------

const row = (cells: readonly string[]): string => `| ${cells.join(" | ")} |`;

const groupRow = (group: MapGroup, shapes: number): string => {
  const { set, source, area } = group;
  const links = ALL_TYPES.map((type) =>
    set.types.includes(type)
      ? `[${type}](../maps/${outputStem(source, area.slug, type)}.json)`
      : "",
  );
  const count = shapes.toLocaleString("en-GB");
  return row([
    LEVEL_NAMES[source.level],
    String(source.year),
    area.label,
    shapes > MAX_AREAS ? `${count} (over Power BI's limit)` : count,
    ...links,
    `[CSV](../data/synthetic/${syntheticFile(source.level, source.year)})`,
  ]);
};

const sourceRows = (): readonly string[] =>
  [...new Map(MAP_SETS.flatMap((set) => set.sources).map((source) => [source.service, source])).values()]
    .toSorted((a, b) => a.level.localeCompare(b.level) || a.year - b.year)
    .map((source) =>
      row([LEVEL_NAMES[source.level], String(source.year), PROVIDER_NAMES[source.provider], `\`${source.service}\``]),
    );

// ---------- I/O ----------

const shapeCount = async (group: MapGroup): Promise<number> => {
  const path = join(ROOT, "maps", `${outputStem(group.source, group.area.slug, "geographic")}.json`);
  const topology = (await Bun.file(path).json()) as {
    objects: Record<string, { geometries?: unknown[] }>;
  };
  return Object.values(topology.objects).reduce(
    (sum, object) => sum + (object.geometries?.length ?? 0),
    0,
  );
};

const main = async (): Promise<void> => {
  const counted = await Promise.all(
    MAP_GROUPS.map(async (group) => [group, await shapeCount(group)] as const),
  );
  const total = MAP_GROUPS.reduce((sum, group) => sum + group.set.types.length, 0);
  const sections = MAP_SETS.map((set) =>
    [
      `## ${set.title}`,
      "",
      row(["Level", "Version", "Area", "Shapes", "Geographic", "Hexmap", "Geogrid", "Sample data"]),
      row(["---", "---", "---", "---", "---", "---", "---", "---"]),
      ...counted.filter(([group]) => group.set === set).map(([group, shapes]) => groupRow(group, shapes)),
    ].join("\n"),
  );
  const document = [
    "# Map files",
    "",
    "<!-- Generated by `bun run catalogue`. Do not edit by hand. -->",
    "",
    `Every map file in this repository: ${total} files. Each link opens the file on GitHub, where **Download raw file** saves it.`,
    "",
    "- **Shapes** is the number of areas in the file. Power BI's Shape map plots at most 1,500.",
    "- Every map has a preview image at the same path under [`images/`](../images), ending in `.svg`.",
    "- **Sample data** is made up. It is not real statistics.",
    "",
    ...sections.flatMap((section) => [section, ""]),
    "## Where the boundaries come from",
    "",
    row(["Level", "Version", "Publisher", "Layer"]),
    row(["---", "---", "---", "---"]),
    ...sourceRows(),
    "",
  ].join("\n");
  await writeFile(OUTPUT, document);
  console.info(`Wrote docs/map-files.md: ${total} map files in ${MAP_SETS.length} sets.`);
};

await main();
